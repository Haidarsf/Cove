// Dumps: with capture on, nginx passes VAR_DUMPER_FORMAT=server to PHP, so
// Symfony VarDumper (Laravel's dump()/dd()) sends each dump to this listener
// instead of the page. Payloads are serialized PHP objects, so a PHP helper
// renders them with the project's own VarDumper.

type Dump struct {
	ID     int    `json:"id"`
	Time   string `json:"time"`
	Text   string `json:"text"`
	File   string `json:"file,omitempty"`
	Line   int    `json:"line,omitempty"`
	Name   string `json:"name,omitempty"`
	URI    string `json:"uri,omitempty"`
	Method string `json:"method,omitempty"`
	Site   string `json:"site,omitempty"`
}

var (
	dumpMu   sync.Mutex
	dumps    []Dump
	dumpSeq  int
	dumpSubs = map[chan Dump]bool{}
)

func dumpAddr() string { return fmt.Sprintf("127.0.0.1:%d", getConfig().Ports.Dumps) }

func startDumpServer() {
	ln, err := net.Listen("tcp", dumpAddr())
	if err != nil {
		log.Printf("dump server: %v", err)
		return
	}
	for {
		conn, err := ln.Accept()
		if err != nil {
			return
		}
		go func(c net.Conn) {
			defer c.Close()
			sc := bufio.NewScanner(c)
			sc.Buffer(make([]byte, 1<<20), 64<<20)
			for sc.Scan() {
				if d, err := renderDump(sc.Text()); err != nil {
					log.Printf("dump: %v", err)
				} else {
					addDump(d)
				}
			}
		}(conn)
	}
}

func addDump(d Dump) {
	dumpMu.Lock()
	dumpSeq++
	d.ID, d.Time = dumpSeq, time.Now().Format("15:04:05")
	dumps = append(dumps, d)
	if len(dumps) > 300 {
		dumps = dumps[len(dumps)-300:]
	}
	for ch := range dumpSubs {
		select {
		case ch <- d:
		default:
		}
	}
	dumpMu.Unlock()
}

// renderDump runs the PHP helper on one base64 payload line.
func renderDump(line string) (Dump, error) {
	var d Dump
	c := getConfig()
	php := filepath.Join(phpDir(c.DefaultPHP), "php.exe")
	if !fileExists(php) {
		return d, fmt.Errorf("no PHP to render dumps")
	}
	script := filepath.Join(confDir(), "dump-render.php")
	os.WriteFile(script, []byte(dumpRenderPHP), 0o644)
	cmd := hidden(exec.Command(php, "-c", filepath.Join(phpDir(c.DefaultPHP), "php.ini"), script))
	cmd.Stdin = strings.NewReader(line)
	out, err := cmd.Output()
	if err != nil {
		return d, fmt.Errorf("render: %v", err)
	}
	if err := json.Unmarshal(out, &d); err != nil {
		return d, fmt.Errorf("render: %s", strings.TrimSpace(string(out)))
	}
	if s, ok := siteForDir(filepath.Dir(d.File)); ok && d.File != "" {
		d.Site = s.Host
	}
	return d, nil
}

const dumpRenderPHP = `<?php
// Generated by Cove: renders one VarDumper ServerDumper payload as JSON.
$payload = base64_decode(trim(stream_get_contents(STDIN)), true);
// First pass without classes, just to read the context (plain arrays).
$plain = $payload === false ? false : @unserialize($payload, ['allowed_classes' => false]);
if (!is_array($plain)) { exit(json_encode(['text' => '(unreadable dump payload)'])); }
$ctx = is_array($plain[1] ?? null) ? $plain[1] : [];
$file = $ctx['source']['file'] ?? '';
for ($d = dirname($file); $file && $d !== dirname($d); $d = dirname($d)) {
    if (is_file($d . '/vendor/autoload.php')) { require $d . '/vendor/autoload.php'; break; }
}
$text = '';
if (class_exists(Symfony\Component\VarDumper\Dumper\CliDumper::class)) {
    [$data] = unserialize($payload);
    $dumper = new Symfony\Component\VarDumper\Dumper\CliDumper(null, null, 0);
    $dumper->setColors(false);
    $text = $dumper->dump($data, true);
}
echo json_encode([
    'text' => rtrim($text),
    'file' => $file,
    'line' => $ctx['source']['line'] ?? 0,
    'name' => $ctx['source']['name'] ?? '',
    'uri' => $ctx['request']['uri'] ?? ($ctx['cli']['command_line'] ?? ''),
    'method' => $ctx['request']['method'] ?? '',
], JSON_INVALID_UTF8_SUBSTITUTE);
`

func apiDumpStream(w http.ResponseWriter, r *http.Request) {
	w.Header().Set("Content-Type", "text/event-stream")
	w.Header().Set("Cache-Control", "no-cache")
	fl, _ := w.(http.Flusher)
	ch := make(chan Dump, 16)
	dumpMu.Lock()
	dumpSubs[ch] = true
	dumpMu.Unlock()
	defer func() { dumpMu.Lock(); delete(dumpSubs, ch); dumpMu.Unlock() }()
	fmt.Fprint(w, ": hello\n\n")
	if fl != nil {
		fl.Flush()
	}
	for {
		select {
		case <-r.Context().Done():
			return
		case d := <-ch:
			j, _ := json.Marshal(d)
			fmt.Fprintf(w, "data: %s\n\n", j)
			if fl != nil {
				fl.Flush()
			}
		case <-time.After(25 * time.Second):
			fmt.Fprint(w, ": ping\n\n")
			if fl != nil {
				fl.Flush()
			}
		}
	}
}

func listDumps() []Dump {
	dumpMu.Lock()
	defer dumpMu.Unlock()
	return append([]Dump{}, dumps...)
}

func clearDumps() {
	dumpMu.Lock()
	dumps = nil
	dumpMu.Unlock()
}

// dumperParams points VarDumper at Cove when capture is on.
func dumperParams() string {
	if !getConfig().CaptureDumps {
		return ""
	}
	return fmt.Sprintf("            fastcgi_param VAR_DUMPER_FORMAT server;\n            fastcgi_param VAR_DUMPER_SERVER %s;\n", dumpAddr())
}
