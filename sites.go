package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

type Site struct {
	Name      string `json:"name"`
	Host      string `json:"host"`
	URL       string `json:"url"`
	Path      string `json:"path"`
	Root      string `json:"root"`
	Secure    bool   `json:"secure"`
	PHP       string `json:"php"`
	Isolated  bool   `json:"isolated"`
	Linked    bool   `json:"linked"`
	Framework string `json:"framework"`
	Share     string `json:"share,omitempty"` // public tunnel URL while shared
}

var siteNameRe = regexp.MustCompile(`[^a-z0-9]+`)

// slug turns a folder name into a hostname label: "xs-com - Copy" -> "xs-com-copy".
func slug(s string) string {
	return strings.Trim(siteNameRe.ReplaceAllString(strings.ToLower(s), "-"), "-")
}

// listSites merges parked folders and explicit links (links win on name clashes).
func listSites() []Site {
	c := getConfig()
	found := map[string]Site{}
	for _, parked := range c.Paths {
		entries, _ := os.ReadDir(parked)
		for _, e := range entries {
			if !e.IsDir() || strings.HasPrefix(e.Name(), ".") {
				continue
			}
			name := slug(e.Name())
			if name == "" {
				continue
			}
			found[name] = makeSite(c, name, filepath.Join(parked, e.Name()), false)
		}
	}
	for name, path := range c.Links {
		found[name] = makeSite(c, name, path, true)
	}
	out := make([]Site, 0, len(found))
	for _, s := range found {
		out = append(out, s)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}

func findSite(name string) (Site, bool) {
	name = strings.TrimSuffix(strings.ToLower(name), "."+getConfig().TLD)
	for _, s := range listSites() {
		if s.Name == name {
			return s, true
		}
	}
	return Site{}, false
}

// siteForDir resolves the site whose folder contains dir (used by CLI commands
// run without a name, like `cove secure` inside a project).
func siteForDir(d string) (Site, bool) {
	d, _ = filepath.Abs(d)
	best := Site{}
	for _, s := range listSites() {
		p, _ := filepath.Abs(s.Path)
		if strings.EqualFold(d, p) || strings.HasPrefix(strings.ToLower(d), strings.ToLower(p)+`\`) {
			if len(p) > len(best.Path) {
				best = s
			}
		}
	}
	return best, best.Name != ""
}

func makeSite(c Config, name, path string, linked bool) Site {
	s := Site{Name: name, Path: path, Linked: linked, Host: name + "." + c.TLD}
	s.Root = path
	for _, sub := range []string{"public", "web", "public_html", "htdocs"} {
		if fi, err := os.Stat(filepath.Join(path, sub)); err == nil && fi.IsDir() {
			s.Root = filepath.Join(path, sub)
			break
		}
	}
	switch {
	case fileExists(filepath.Join(path, "artisan")):
		s.Framework = "Laravel"
	case fileExists(filepath.Join(path, "bin", "console")) && fileExists(filepath.Join(path, "symfony.lock")):
		s.Framework = "Symfony"
	case fileExists(filepath.Join(path, "wp-config.php")) || fileExists(filepath.Join(path, "wp-load.php")):
		s.Framework = "WordPress"
	case fileExists(filepath.Join(path, "craft")):
		s.Framework = "Craft"
	case fileExists(filepath.Join(s.Root, "index.php")):
		s.Framework = "PHP"
	default:
		s.Framework = "Static"
	}
	s.Secure = c.Secured[name]
	s.Share = shareURL(name)
	s.PHP, s.Isolated = c.DefaultPHP, false
	if v, ok := c.Isolated[name]; ok {
		s.PHP, s.Isolated = v, true
	}
	scheme, port := "http", c.Ports.HTTP
	if s.Secure {
		scheme, port = "https", c.Ports.HTTPS
	}
	s.URL = fmt.Sprintf("%s://%s", scheme, s.Host)
	if (scheme == "http" && port != 80) || (scheme == "https" && port != 443) {
		s.URL += fmt.Sprintf(":%d", port)
	}
	return s
}

// ---------- nginx config ----------

func nginxPrefix() string {
	p := dir("run", "nginx")
	for _, d := range []string{"logs", "temp", "temp/client_body_temp", "temp/proxy_temp", "temp/fastcgi_temp", "temp/uwsgi_temp", "temp/scgi_temp"} {
		os.MkdirAll(filepath.Join(p, d), 0o755)
	}
	return p
}

func nginxConfPath() string { return filepath.Join(confDir(), "nginx.conf") }

func writeNginxConf() error {
	c := getConfig()
	conf := fwd(filepath.Join(nginxDir(), "conf"))
	var b strings.Builder
	fmt.Fprintf(&b, `# Generated by Cove — edits are overwritten. Add custom blocks in config/nginx.d/*.conf
worker_processes 1;
error_log "%s" warn;
pid "%s";

events { worker_connections 2048; }

http {
    include "%s/mime.types";
    default_type application/octet-stream;
    sendfile on;
    tcp_nopush on;
    keepalive_timeout 65;
    server_names_hash_bucket_size 128;
    client_max_body_size 512M;
    gzip on;
    gzip_types text/css application/javascript application/json image/svg+xml text/plain;
    log_format cove '$time_local  $status  $request_method $host$request_uri  ${request_time}s';
    access_log "%s" cove;

`, fwd(filepath.Join(logDir(), "nginx-error.log")), fwd(filepath.Join(nginxPrefix(), "logs", "nginx.pid")),
		conf, fwd(filepath.Join(logDir(), "nginx-access.log")))

	for _, v := range branchesInUse() {
		fmt.Fprintf(&b, "    upstream %s {\n", phpUpstream(v))
		for i := 0; i < c.PHPWorkers; i++ {
			fmt.Fprintf(&b, "        server 127.0.0.1:%d max_fails=0;\n", phpPort(v, i))
		}
		b.WriteString("    }\n")
	}

	listen := func(secure bool) string {
		if secure {
			return fmt.Sprintf("listen 127.0.0.1:%d ssl;\n        http2 on;", c.Ports.HTTPS)
		}
		return fmt.Sprintf("listen 127.0.0.1:%d;", c.Ports.HTTP)
	}

	// Fallback + dashboard.
	fmt.Fprintf(&b, `
    server {
        listen 127.0.0.1:%d default_server;
        server_name _;
        location / { proxy_pass http://127.0.0.1:%d/notfound; proxy_set_header Host $host; }
    }
    server {
        %s
        server_name cove.%s;
        location / {
            proxy_pass http://127.0.0.1:%d;
            proxy_http_version 1.1;
            proxy_set_header Connection "";
            proxy_buffering off;
        }
    }
`, c.Ports.HTTP, c.Ports.API, listen(false), c.TLD, c.Ports.API)

	installed := map[string]bool{}
	for _, v := range installedPHP() {
		installed[v] = true
	}
	for _, s := range listSites() {
		up := ""
		if installed[s.PHP] {
			up = phpUpstream(s.PHP)
		}
		names := fmt.Sprintf("%s *.%s", s.Host, s.Host)
		if h := shareHost(s.Name); h != "" {
			names += " " + h
		}
		if s.Secure {
			fmt.Fprintf(&b, "\n    server {\n        %s\n        server_name %s;\n        return 301 https://$host%s$request_uri;\n    }\n",
				listen(false), names, portSuffix(c.Ports.HTTPS, 443))
			b.WriteString(siteServer(s, names, listen(true), up, true))
		} else {
			b.WriteString(siteServer(s, names, listen(false), up, false))
		}
	}
	fmt.Fprintf(&b, "\n    include \"%s/*.conf\";\n}\n", fwd(dir("config", "nginx.d")))
	return os.WriteFile(nginxConfPath(), []byte(b.String()), 0o644)
}

func portSuffix(port, def int) string {
	if port == def {
		return ""
	}
	return fmt.Sprintf(":%d", port)
}

func siteServer(s Site, names, listen, upstream string, secure bool) string {
	var b strings.Builder
	fmt.Fprintf(&b, `
    server {
        %s
        server_name %s;
        root "%s";
        index index.php index.html index.htm;
        charset utf-8;
`, listen, names, fwd(s.Root))
	if secure {
		fmt.Fprintf(&b, "        ssl_certificate \"%s\";\n        ssl_certificate_key \"%s\";\n",
			fwd(filepath.Join(certDir(), s.Host+".crt")), fwd(filepath.Join(certDir(), s.Host+".key")))
	}
	b.WriteString(`        location = /favicon.ico { access_log off; log_not_found off; }
        location = /robots.txt  { access_log off; log_not_found off; }
        location ~ /\.(?!well-known).* { deny all; }
`)
	if upstream == "" || s.Framework == "Static" {
		// Like WAMP: folders without an index page get a file listing.
		b.WriteString("        autoindex on;\n        location / { try_files $uri $uri/ =404; }\n    }\n")
		return b.String()
	}
	https := "off"
	if secure {
		https = "on"
	}
	fmt.Fprintf(&b, `        location / { try_files $uri $uri/ /index.php?$query_string; }
        location ~ \.php$ {
            try_files $fastcgi_script_name =404;
            fastcgi_split_path_info ^(.+\.php)(/.+)$;
            fastcgi_pass %s;
            fastcgi_index index.php;
            include "%s/fastcgi_params";
            fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;
            fastcgi_param PATH_INFO $fastcgi_path_info;
            fastcgi_param HTTPS %s;
%s            fastcgi_buffers 16 32k;
            fastcgi_buffer_size 64k;
            fastcgi_read_timeout 300;
            fastcgi_next_upstream error timeout;
        }
    }
`, upstream, fwd(filepath.Join(nginxDir(), "conf")), https, dumperParams())
	return b.String()
}
