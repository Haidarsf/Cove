// Extensions Laravel (and most frameworks) expect, enabled when present.
var phpExtensions = []string{
	"bz2", "curl", "fileinfo", "gd", "gettext", "gmp", "intl", "mbstring", "exif",
	"mysqli", "openssl", "pdo_mysql", "pdo_pgsql", "pdo_sqlite", "pgsql", "sodium",
	"sqlite3", "xsl", "zip", "ftp", "sockets",
}

func writePHPIni(branch string) error {
	d := phpDir(branch)
	c := getConfig()
	var b strings.Builder
	b.WriteString("; Generated by Cove. Put your own overrides in php.local.ini next to this file.\n[PHP]\n")
	fmt.Fprintf(&b, `engine = On
short_open_tag = Off
memory_limit = 512M
max_execution_time = 120
max_input_time = 120
max_input_vars = 5000
post_max_size = 512M
upload_max_filesize = 512M
display_errors = On
display_startup_errors = On
log_errors = On
; Deprecations are logged by frameworks themselves; echoing them would break headers.
error_reporting = E_ALL & ~E_DEPRECATED
error_log = "%s"
variables_order = "EGPCS"
request_order = "GP"
output_buffering = 4096
realpath_cache_size = 16M
realpath_cache_ttl = 600
extension_dir = "%s"
sys_temp_dir = "%s"
upload_tmp_dir = "%s"
date.timezone = UTC
cgi.fix_pathinfo = 1
fastcgi.impersonate = 1

[mail function]
SMTP = 127.0.0.1
smtp_port = %d
sendmail_from = cove@localhost

[curl]
curl.cainfo = "%s"

[openssl]
openssl.cafile = "%s"

[Session]
session.save_path = "%s"

`, fwd(filepath.Join(logDir(), "php-"+branch+"-errors.log")), fwd(filepath.Join(d, "ext")),
		fwd(dir("tmp")), fwd(dir("tmp")), c.Ports.SMTP,
		fwd(filepath.Join(certDir(), "cacert.pem")), fwd(filepath.Join(certDir(), "cacert.pem")),
		fwd(dataDir("sessions")))

	for _, ext := range phpExtensions {
		if fileExists(filepath.Join(d, "ext", "php_"+ext+".dll")) {
			fmt.Fprintf(&b, "extension=%s\n", ext)
		}
	}
	if fileExists(filepath.Join(d, "ext", "php_opcache.dll")) {
		b.WriteString("zend_extension=opcache\n")
	}
	b.WriteString(`
[opcache]
opcache.enable = 1
opcache.enable_cli = 0
opcache.memory_consumption = 256
opcache.interned_strings_buffer = 32
opcache.max_accelerated_files = 50000
opcache.validate_timestamps = 1
opcache.revalidate_freq = 0
opcache.jit = tracing
opcache.jit_buffer_size = 64M
`)
	if local, err := os.ReadFile(filepath.Join(d, "php.local.ini")); err == nil {
		b.WriteString("\n; ---- php.local.ini ----\n")
		b.Write(local)
	}
	return os.WriteFile(filepath.Join(d, "php.ini"), []byte(b.String()), 0o644)
}

// phpPort is deterministic per branch so nginx config never has to guess:
// 8.4 worker #2 -> 9842.
func phpPort(branch string, worker int) int {
	p := strings.Split(branch, ".")
	return 9000 + atoi(p[0])*100 + atoi(p[1])*10 + worker
}

func phpUpstream(branch string) string { return "php" + strings.ReplaceAll(branch, ".", "") }

// branchesInUse is the default version plus every isolated one that is installed.
func branchesInUse() []string {
	c := getConfig()
	set := map[string]bool{}
	installed := map[string]bool{}
	for _, v := range installedPHP() {
		installed[v] = true
	}
	if installed[c.DefaultPHP] {
		set[c.DefaultPHP] = true
	}
	for _, v := range c.Isolated {
		if installed[v] {
			set[v] = true
		}
	}
	var out []string
	for v := range set {
		out = append(out, v)
	}
	sort.Strings(out)
	return out
}

// newPHPPool builds php-cgi workers for one branch. php-cgi on Windows serves one
// request at a time, so we run several and let nginx balance across them.
func newPHPPool(branch string) []*Proc {
	var procs []*Proc
	n := getConfig().PHPWorkers
	for i := 0; i < n; i++ {
		port := phpPort(branch, i)
		procs = append(procs, &Proc{
			Name: fmt.Sprintf("php-%s#%d", branch, i),
			Log:  filepath.Join(logDir(), "php-"+branch+".log"),
			Build: func() *exec.Cmd {
				d := phpDir(branch)
				cmd := exec.Command(filepath.Join(d, "php-cgi.exe"), "-b", fmt.Sprintf("127.0.0.1:%d", port), "-c", filepath.Join(d, "php.ini"))
				cmd.Dir = d
				cmd.Env = append(os.Environ(), "PHP_FCGI_MAX_REQUESTS=2000", "PHPRC="+d)
				return cmd
			},
		})
	}
	return procs
}
